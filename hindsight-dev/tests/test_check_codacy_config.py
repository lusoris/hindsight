def test_header_at_line_21_is_not_evidence(tmp_path: Path, capsys):
    """A generator marker on line 20 counts, while line 21 is outside the 20-line header window."""
    line_20_file = tmp_path / "line_20.py"
    _write_generated(line_20_file, ("# filler\n" * 19) + GENERATED_PY_HEADER)
    (tmp_path / ".codacy.yml").write_text("---\n", encoding="utf-8")
    assert check_mod.main(["--root", str(tmp_path)], today=TODAY) == 1
    assert "line_20.py" in capsys.readouterr().err
    line_20_file.unlink()

    late_file = tmp_path / "late_marker.py"
    _write_generated(late_file, ("# filler\n" * 20) + GENERATED_PY_HEADER)

    # Outside patterns: not flagged as an unexcluded generated file.
    assert check_mod.main(["--root", str(tmp_path)], today=TODAY) == 0

    # Inside a duplication pattern: rejected as hand-written.
    (tmp_path / ".codacy.yml").write_text(_make_codacy_text("late_marker.py"), encoding="utf-8")
    assert check_mod.main(["--root", str(tmp_path)], today=TODAY) == 1
    assert "matches hand-written file late_marker.py" in capsys.readouterr().err


