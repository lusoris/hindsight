#!/usr/bin/env python3
"""Validate .codacy.yml exclusions against category limits, engine scopes, and active files.

Every Codacy exclusion is an exception to a scanner rule, so each list item must sit
directly under a comment of the form

    # category <A|B|C|D>, entry YYYY-MM-DD, expiry YYYY-MM-DD, rule <engine>: <reason>

where the expiry is not past and stays within the category's window from entry
(B 3, C 10, D 120 days), the rule names the engine the item is listed under, and
the path pattern still matches a file.

For ``engines.duplication``, exclusions and generated files must also match in both
directions over the file extensions Codacy's duplication engine scans:

- Forward: every scanned file with allow-listed generator evidence (a header marker in
  its first 20 lines or an entry in ``<dir>/.openapi-generator/FILES``) must match at
  least one ``engines.duplication.exclude_paths`` pattern.
- Reverse: every ``engines.duplication.exclude_paths`` pattern may match only scanned
  files that carry generator evidence, never a hand-written file.
- Non-vacuous: every ``engines.duplication.exclude_paths`` pattern must match at least
  one file whose extension the duplication engine scans.

The reader is an allow-list: any line it does not recognise fails, so a new key in
.codacy.yml has to be taught here first instead of passing unchecked.

usage: check-codacy-config.py [--root ROOT]
"""

from __future__ import annotations

import argparse
import datetime
import itertools
import os
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

BLANK_RE = re.compile(r"^\s*$")
DOC_START_RE = re.compile(r"^---\s*$")
COMMENT_LINE_RE = re.compile(r"^\s*#")
KEY_RE = re.compile(r"^( *)([a-z_]+):\s*$")
LIST_ITEM_RE = re.compile(r'^( +)- "?([^"\s]+)"?\s*$')
COMMENT_RE = re.compile(r"^ *# category ([ABCD]), entry (\S+), expiry (\S+), rule ([a-z_]+): (\S.*)$")
DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")

EXCLUDE_ITEM_INDENT = 6  # Two spaces per level: engines 0, engine 2, exclude_paths 4, its items 6.

INTERVALS: dict[str, int] = {
    "B": 3,
    "C": 10,
    "D": 120,
}

